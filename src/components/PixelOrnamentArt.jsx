/** 共用 RLE 矩形串渲染輔助，避免重複 JSX */
function renderRleRects(rects, colorMap = null) {
  return rects.map(([x, y, w, h, colorOrRole], idx) => (
    <rect
      key={idx}
      x={x}
      y={y}
      width={w}
      height={h}
      fill={colorMap ? colorMap[colorOrRole] : colorOrRole}
    />
  ));
}

/** 共用純像素精靈 SVG 包裝器 */
function PixelSpriteSvg({ viewBox, rects, className = '', colorMap = null }) {
  return (
    <svg
      viewBox={viewBox}
      shapeRendering="crispEdges"
      className={className}
      aria-hidden="true"
    >
      {renderRleRects(rects, colorMap)}
    </svg>
  );
}

